CREATE TABLE dim_date (
    date_id INTEGER PRIMARY KEY,
    full_date DATE NOT NULL UNIQUE,
    day_of_month SMALLINT NOT NULL CHECK (day_of_month BETWEEN 1 AND 31),
    month_number SMALLINT NOT NULL CHECK (month_number BETWEEN 1 AND 12),
    quarter_number SMALLINT NOT NULL CHECK (quarter_number BETWEEN 1 AND 4),
    year_number INTEGER NOT NULL
);

CREATE TABLE dim_customer (
    customer_id INTEGER PRIMARY KEY,
    first_name VARCHAR(40) NOT NULL,
    last_name VARCHAR(20) NOT NULL,
    company VARCHAR(80),
    city VARCHAR(40),
    state VARCHAR(40),
    country VARCHAR(40),
    postal_code VARCHAR(10)
);

CREATE TABLE dim_track (
    track_id INTEGER PRIMARY KEY,
    track_name VARCHAR(200) NOT NULL,
    composer VARCHAR(220),
    milliseconds INTEGER NOT NULL,
    bytes INTEGER,
    catalog_unit_price NUMERIC(10,2) NOT NULL,
    album_title VARCHAR(160),
    artist_name VARCHAR(120),
    genre_name VARCHAR(120),
    media_type_name VARCHAR(120)
);

CREATE TABLE dim_employee (
    employee_id INTEGER PRIMARY KEY,
    first_name VARCHAR(20) NOT NULL,
    last_name VARCHAR(20) NOT NULL,
    job_title VARCHAR(30),
    city VARCHAR(40),
    country VARCHAR(40)
);

CREATE TABLE dim_billing_location (
    billing_location_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    billing_address VARCHAR(70),
    billing_city VARCHAR(40),
    billing_state VARCHAR(40),
    billing_country VARCHAR(40),
    billing_postal_code VARCHAR(10)
);

CREATE TABLE fact_sales (
    invoice_line_id INTEGER PRIMARY KEY,
    invoice_id INTEGER NOT NULL,
    date_id INTEGER NOT NULL,
    customer_id INTEGER NOT NULL,
    track_id INTEGER NOT NULL,
    employee_id INTEGER,
    billing_location_id INTEGER NOT NULL,
    invoice_timestamp TIMESTAMP NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(10,2) NOT NULL CHECK (unit_price >= 0),
    sales_amount NUMERIC(18,2) GENERATED ALWAYS AS (quantity * unit_price) STORED,
    CONSTRAINT fk_sales_date FOREIGN KEY (date_id) REFERENCES dim_date(date_id),
    CONSTRAINT fk_sales_customer FOREIGN KEY (customer_id) REFERENCES dim_customer(customer_id),
    CONSTRAINT fk_sales_track FOREIGN KEY (track_id) REFERENCES dim_track(track_id),
    CONSTRAINT fk_sales_employee FOREIGN KEY (employee_id) REFERENCES dim_employee(employee_id),
    CONSTRAINT fk_sales_billing_location FOREIGN KEY (billing_location_id) REFERENCES dim_billing_location(billing_location_id)
);

CREATE INDEX idx_fact_sales_date ON fact_sales(date_id);
CREATE INDEX idx_fact_sales_customer ON fact_sales(customer_id);
CREATE INDEX idx_fact_sales_track ON fact_sales(track_id);
CREATE INDEX idx_fact_sales_employee ON fact_sales(employee_id);
CREATE INDEX idx_fact_sales_billing_location ON fact_sales(billing_location_id);
CREATE INDEX idx_fact_sales_invoice ON fact_sales(invoice_id);